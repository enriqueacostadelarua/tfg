#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
A simple Python script to merge multiple C++ source (.cpp, .h) files
from a single directory into one file for easy sharing or submission.

It separates the content of each file with a clear comment block
indicating the original filename.
"""

import os
import sys

# --- Configuration ---

# The name of the final merged file.
OUTPUT_FILENAME = "merged_code.cpp"

# File extensions to search for. Headers are processed first.
HEADER_EXTENSIONS = ('.h', '.hpp')
SOURCE_EXTENSIONS = ('.cpp', 'cxx', '.cc')

# --- End of Configuration ---


def create_separator(filename):
    """Creates a formatted comment string to separate files."""
    banner_line = "//" + "=" * 78
    file_line = f"// FILE: {filename}"
    return f"\n{banner_line}\n{file_line}\n{banner_line}\n\n"


def main():
    """Main function to find, merge, and write the C++ source files."""
    
    script_name = os.path.basename(sys.argv[0])
    current_directory = os.getcwd()
    
    print(f"Running script in: {current_directory}")
    print(f"Output will be saved to: {OUTPUT_FILENAME}\n")

    # Find all relevant files in the current directory
    all_files_in_dir = os.listdir(current_directory)

    # Separate headers and sources to control merge order
    header_files = sorted([f for f in all_files_in_dir if f.endswith(HEADER_EXTENSIONS)])
    source_files = sorted([f for f in all_files_in_dir if f.endswith(SOURCE_EXTENSIONS)])
    
    files_to_merge = header_files + source_files

    # --- Safety Checks ---
    # Exclude the output file itself to prevent it from being merged on subsequent runs
    if OUTPUT_FILENAME in files_to_merge:
        print(f"Note: Excluding '{OUTPUT_FILENAME}' from the merge list.")
        files_to_merge.remove(OUTPUT_FILENAME)

    # Exclude the script itself
    if script_name in files_to_merge:
        files_to_merge.remove(script_name)

    if not files_to_merge:
        print("Error: No source files (.cpp, .h, etc.) found in this directory. Exiting.")
        return

    print("Found the following files to merge (headers first):")
    for f in files_to_merge:
        print(f"  - {f}")
    print("-" * 20)

    try:
        # Open the output file in write mode
        with open(OUTPUT_FILENAME, 'w', encoding='utf-8') as outfile:
            # Add a header to the merged file itself
            outfile.write(f"// This file was automatically generated by '{script_name}'\n")
            outfile.write(f"// Merged files: {', '.join(files_to_merge)}\n")

            # Iterate through the list of files to merge
            for filename in files_to_merge:
                print(f"-> Processing {filename}...")
                
                # Write the separator comment to the output file
                outfile.write(create_separator(filename))
                
                try:
                    # Open and read the source file
                    with open(filename, 'r', encoding='utf-8') as infile:
                        content = infile.read()
                        outfile.write(content)
                        # Ensure there's a newline at the end of the file's content
                        if not content.endswith('\n'):
                            outfile.write('\n')

                except Exception as e:
                    error_msg = f"// [ERROR] Could not read file {filename}: {e}"
                    print(f"   ! {error_msg}")
                    outfile.write(f"{error_msg}\n")

    except IOError as e:
        print(f"\n[CRITICAL ERROR] Could not write to output file '{OUTPUT_FILENAME}'.")
        print(f"Reason: {e}")
        return

    print(f"\n✅ Success! All code has been merged into '{OUTPUT_FILENAME}'.")


if __name__ == "__main__":
    main()